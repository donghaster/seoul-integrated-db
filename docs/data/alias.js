// 손으로 적는다 — 한 단지처럼 불리는데 신고는 따로 오는 곳들.
//
// 국토교통부 신고는 등기된 이름 그대로 온다. 그런데 현장에서는 같은 해에
// 같은 자리에 함께 지어 올린 두 단지를 한 이름으로 부른다. 노원구 하계동
// 현대와 우성이 그렇다 — 1988년 입주, 총 12개 동 1,320세대를 평형만 나눠
// 지었고, 부동산에서는 '현대,우성' 또는 '현우'로 내건다.
//
// 그래서 손님이 '현우'라고 물으시면 찾기에서 아무것도 안 나왔다. 여기에
// 적어 두면 그 말로도 두 단지가 함께 잡히고, 단지 카드에서 서로 오갈 수 있다.
//
//   q    : 손님이 말할 법한 이름들(띄어쓰기·가운뎃점은 알아서 지운다)
//   keys : "자치구|법정동|단지" — 실거래 신고에 오는 이름 그대로
//   name : 묶어서 부를 이름. 이 이름으로 '묶음 단지'가 하나 생겨, 평형별
//          분석과 인근 비교를 한자리에서 한다(순위·지도에는 끼지 않는다)
//   note : 왜 한 단지처럼 부르는지. 화면에 그대로 나온다
window.APT_ALIAS = [
  {
    q: ["현대우성", "현우", "현대,우성", "우성현대"],
    keys: ["노원구|하계동|현대", "노원구|하계동|우성"],
    name: "현대·우성",
    note: "1988년에 평형을 나눠 함께 지은 한 단지 — 현장에서는 '현대우성(현우)'로 부름",
  },
];
